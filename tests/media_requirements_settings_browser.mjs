import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import fs from 'node:fs';
const {chromium}=await import(pathToFileURL(process.env.RYOKAN_PLAYWRIGHT_MODULE).href);
const browser=await chromium.launch({executablePath:process.env.RYOKAN_CHROME_BIN||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.route('**/*',route=>new URL(route.request().url()).origin===process.argv[2]?route.continue():route.abort());
const screenshots=process.env.RYOKAN_REQUIREMENTS_SCREENSHOTS||'/private/tmp/ryokan-requirements-screenshots';fs.mkdirSync(screenshots,{recursive:true});
try {
    await page.goto(process.argv[2]+'/settings?tab=quality');
    await page.waitForFunction(()=>!!window.htmx);
    await page.locator('#media_requirements_enabled').selectOption('1');
    await page.locator('#minimum_resolution').selectOption('720');
    await page.locator('#target_resolution').selectOption('1080');
    await page.locator('#minimum_subtitle_check').selectOption('1');
    await page.locator('#target_subtitle_check').selectOption('1');
    await page.screenshot({path:screenshots+'/settings-desktop.png',fullPage:true});
    await page.locator('#required_subtitle_languages').fill('Spanish');
    await page.locator('#target_resolution').selectOption('2160');
    await page.locator('#minimum_subtitle_check').selectOption('0');
    await page.locator('#settings-quality-region').getByRole('button',{name:'Save Settings',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#required_subtitle_languages')?.value==='es');
    await page.reload();
    assert.equal(await page.locator('#target_resolution').inputValue(),'2160');
    assert.equal(await page.locator('#minimum_subtitle_check').inputValue(),'0');
    assert.equal(await page.locator('#required_subtitle_languages').inputValue(),'es');
    await page.locator('#minimum_resolution').selectOption('1080');
    await page.locator('#target_resolution').selectOption('720');
    await page.locator('#settings-quality-region').getByRole('button',{name:'Save Settings',exact:true}).click();
    await page.locator('#settings-quality-region .alert-error').waitFor();
    assert.equal(await page.locator('#target_resolution').inputValue(),'720');
    assert.equal(await page.locator('#required_subtitle_languages').inputValue(),'es');
    await page.reload();assert.equal(await page.locator('#target_resolution').inputValue(),'2160');
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:screenshots+'/settings-mobile.png',fullPage:true});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.locator('.quality-advanced > summary').focus();await page.keyboard.press('Enter');
    assert.ok(await page.locator('.quality-advanced').getAttribute('open')!==null);
    await page.locator('#required_subtitle_languages').focus();assert.equal(await page.locator('#required_subtitle_languages').evaluate(el=>el===document.activeElement),true);
    assert.deepEqual(errors,[]);
    console.log('PASS requirements settings: English/1080 defaults, Spanish/4K save, rejection/draft recovery, mobile overflow, keyboard controls.');
} finally {await browser.close();}
